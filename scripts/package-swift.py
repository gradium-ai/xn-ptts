#!/usr/bin/env python3
"""Package the ptts Swift release, and keep the root Package.swift pinned to a release framework.

  package --framework ZIP [--tag vX]  the release package in dist/: a versioned framework URL
                                      and the exact checksum of ZIP
  pin [--run ID]                      pin the root Package.swift to the framework a main run of
                                      the native packages workflow built, for this version
  fetch --tag vX --output DIR         in a tag run: download the framework the root Package.swift
                                      pins, from the main run that built it, and check its checksum
  check [--write]                     fail if the root Package.swift no longer matches
                                      ios/PhononTTS/Package.swift (--write regenerates it)

The root Package.swift is what Swift Package Manager and the Swift Package Index read from a git
tag, so a tag must point at a commit whose root manifest has that release's URL and checksum. The
framework is therefore built once, on main, and reused at the tag rather than rebuilt: two builds
of the same commit do not give the same archive.
"""

import argparse
import hashlib
import json
from pathlib import Path
import re
import shutil
import subprocess
import sys
import tempfile
import zipfile

ROOT = Path(__file__).resolve().parents[1]
SOURCE_MANIFEST = ROOT / "ios/PhononTTS/Package.swift"
ROOT_MANIFEST = ROOT / "Package.swift"
WORKFLOW = "cli-release.yml"
ARTIFACT = "swift-package"
FRAMEWORK = "PhononCore.xcframework.zip"
URL = "https://github.com/gradium-ai/xn-ptts/releases/download/v{version}/" + FRAMEWORK
LOCAL_TARGET = '.binaryTarget(name: "PhononCore", path: "PhononCore.xcframework")'
SOURCES = "ios/PhononTTS/Sources/PhononTTS"
# What the framework is built from. A main run whose commit differs from the tagged commit in
# none of these built the same framework the tag would.
FRAMEWORK_INPUTS = (
    "ptts/",
    "ptts-ffi/",
    "ptts-coreml/",
    "ios/",
    "Cargo.toml",
    "Cargo.lock",
    ".github/actions/setup-rust/",
    f".github/workflows/{WORKFLOW}",
)
ROOT_HEADER = (
    "// Generated by scripts/package-swift.py from ios/PhononTTS/Package.swift; edit that file.\n"
    "// This is the package Swift Package Manager reads from a git tag of this repository. It pins\n"
    "// the compiled core of the release it was tagged for, by URL and exact checksum.\n"
)


def workspace_version():
    import tomllib

    return tomllib.loads((ROOT / "Cargo.toml").read_text())["workspace"]["package"]["version"]


def sha256(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def release_manifest(version, digest, sources=None):
    """ios/PhononTTS/Package.swift with the binary target fetched by URL and checksum."""
    text = SOURCE_MANIFEST.read_text()
    if text.count(LOCAL_TARGET) != 1:
        sys.exit(f"{SOURCE_MANIFEST.relative_to(ROOT)} no longer has the expected binary target")
    # The comment above the local target describes the local build, so it goes with it.
    text = re.sub(
        r"(?:        //.*\n)*        " + re.escape(LOCAL_TARGET),
        lambda _: '        .binaryTarget(\n'
        '            name: "PhononCore",\n'
        f'            url: "{URL.format(version=version)}",\n'
        f'            checksum: "{digest}"\n'
        '        )',
        text,
    )
    if sources:
        dependencies = '            name: "PhononTTS",\n            dependencies: ["PhononCore"],\n'
        if text.count(dependencies) != 1:
            sys.exit(f"{SOURCE_MANIFEST.relative_to(ROOT)} no longer has the expected PhononTTS target")
        text = text.replace(dependencies, f'{dependencies}            path: "{sources}",\n')
        first, rest = text.split("\n", 1)
        text = f"{first}\n{ROOT_HEADER}{rest}"
    return text


def root_pin():
    """The version and checksum the root Package.swift pins."""
    text = ROOT_MANIFEST.read_text()
    url = re.escape(URL).replace(r"\{version\}", r"(?P<version>[^/\"]+)")
    match = re.search(rf'url: "{url}",\s*checksum: "(?P<digest>[0-9a-f]{{64}})"', text)
    if not match:
        sys.exit("the root Package.swift has no release framework URL and checksum")
    return match["version"], match["digest"]


def git(*args):
    return subprocess.run(["git", "-C", str(ROOT), *args], check=True, capture_output=True, text=True).stdout


def builds_same_framework(sha, head):
    """Whether a commit differs from head only outside the framework's inputs."""
    if subprocess.run(["git", "-C", str(ROOT), "cat-file", "-e", f"{sha}^{{commit}}"],
                      capture_output=True).returncode:
        git("fetch", "--quiet", "--no-tags", "--depth=1", "origin", sha)
    # --no-renames: a file moved out of an input directory still counts as a change there.
    changed = git("diff", "--name-only", "--no-renames", sha, head).splitlines()
    return not any(path.startswith(FRAMEWORK_INPUTS) for path in changed)


def candidate_runs(head):
    """Successful main runs of the release workflow that built head's framework, newest first."""
    runs = json.loads(subprocess.check_output([
        "gh", "run", "list", "--workflow", WORKFLOW, "--branch", "main", "--status", "success",
        "--limit", "100", "--json", "databaseId,headSha,event",
    ], cwd=ROOT, text=True))
    for run in runs:
        # Only runs of this repository's own main: a fork's pull request can be named main too.
        if run["event"] in ("push", "workflow_dispatch") and builds_same_framework(run["headSha"], head):
            yield run


def download_framework(run, folder):
    subprocess.run(["gh", "run", "download", str(run["databaseId"]), "--name", ARTIFACT,
                    "--dir", str(folder)], cwd=ROOT, check=True)
    return Path(folder) / FRAMEWORK


def package(args):
    version = workspace_version()
    if args.tag and args.tag != f"v{version}":
        sys.exit(f"tag {args.tag} does not match workspace version {version}")
    framework = args.framework.resolve(strict=True)
    with zipfile.ZipFile(framework) as archive:
        if "PhononCore.xcframework/Info.plist" not in archive.namelist():
            sys.exit("framework zip must contain PhononCore.xcframework at its root")
    args.output.mkdir(parents=True, exist_ok=True)
    destination = args.output / FRAMEWORK
    if destination.resolve() != framework:
        shutil.copy2(framework, destination)
    digest = sha256(destination)
    if args.tag and root_pin() != (version, digest):
        sys.exit(f"the root Package.swift does not pin this framework for {args.tag}")
    manifest = release_manifest(version, digest)
    name = f"ptts-swift-{version}"
    archive_path = args.output / f"{name}.zip"
    with tempfile.TemporaryDirectory() as temp:
        folder = Path(temp) / name
        folder.mkdir()
        (folder / "Package.swift").write_text(manifest)
        shutil.copytree(ROOT / "ios/PhononTTS/Sources", folder / "Sources")
        shutil.copy2(ROOT / "ios/PhononTTS/README.md", folder / "README.md")
        for license_file in ("LICENSE-MIT", "LICENSE-APACHE"):
            shutil.copy2(ROOT / license_file, folder / license_file)
        with zipfile.ZipFile(archive_path, "w", compression=zipfile.ZIP_DEFLATED) as archive:
            for file in sorted(folder.rglob("*")):
                if file.is_file():
                    archive.write(file, f"{name}/{file.relative_to(folder)}")
    checksums = args.output / "SHA256SUMS-apple"
    checksums.write_text(f"{digest}  {destination.name}\n{sha256(archive_path)}  {archive_path.name}\n")
    print(f"{archive_path}: framework checksum {digest}")


def pin(args):
    version = workspace_version()
    head = git("rev-parse", "HEAD").strip()
    if args.run:
        info = json.loads(subprocess.check_output(
            ["gh", "run", "view", str(args.run), "--json", "databaseId,headSha,event"], cwd=ROOT, text=True))
        if not builds_same_framework(info["headSha"], head):
            sys.exit(f"run {args.run} built {info['headSha'][:8]}, whose framework inputs differ from HEAD")
        run = info
    else:
        run = next(candidate_runs(head), None)
        if run is None:
            sys.exit("no successful main run of the native packages workflow built HEAD's framework yet")
    with tempfile.TemporaryDirectory() as temp:
        digest = sha256(download_framework(run, temp))
    ROOT_MANIFEST.write_text(release_manifest(version, digest, SOURCES))
    print(f"Package.swift: v{version} framework from run {run['databaseId']} "
          f"(commit {run['headSha'][:8]}), checksum {digest}")
    print(f"Commit Package.swift alone, tag that commit v{version} and push the tag.")


def fetch(args):
    version, digest = root_pin()
    if args.tag != f"v{version}":
        sys.exit(f"the root Package.swift pins v{version}, not {args.tag}: "
                 f"run scripts/package-swift.py pin before tagging")
    head = git("rev-parse", "HEAD").strip()
    args.output.mkdir(parents=True, exist_ok=True)
    for run in candidate_runs(head):
        with tempfile.TemporaryDirectory() as temp:
            framework = download_framework(run, temp)
            if sha256(framework) == digest:
                shutil.copy2(framework, args.output / FRAMEWORK)
                print(f"pinned framework from run {run['databaseId']} (commit {run['headSha'][:8]})")
                return
    sys.exit(f"no main run that built this commit's framework has checksum {digest}. Its artifact "
             "may have expired, or the run is older than the last 100: rebuild on main and pin again")


def check(args):
    version, digest = root_pin()
    expected = release_manifest(version, digest, SOURCES)
    if ROOT_MANIFEST.read_text() == expected:
        return
    if args.write:
        ROOT_MANIFEST.write_text(expected)
        print("Package.swift regenerated")
        return
    sys.exit("the root Package.swift is out of date with ios/PhononTTS/Package.swift: "
             "run python3 scripts/package-swift.py check --write")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    commands = parser.add_subparsers(dest="command", required=True)
    p = commands.add_parser("package", help="the release package in dist/")
    p.add_argument("--framework", type=Path, required=True)
    p.add_argument("--output", type=Path, default=Path("dist"))
    p.add_argument("--tag", help="require this tag to match the workspace version and the root pin")
    p.set_defaults(func=package)
    p = commands.add_parser("pin", help="pin the root Package.swift to a main run's framework")
    p.add_argument("--run", type=int, help="the workflow run to take the framework from")
    p.set_defaults(func=pin)
    p = commands.add_parser("fetch", help="download the framework the root Package.swift pins")
    p.add_argument("--tag", required=True)
    p.add_argument("--output", type=Path, required=True)
    p.set_defaults(func=fetch)
    p = commands.add_parser("check", help="check the root Package.swift against ios/PhononTTS")
    p.add_argument("--write", action="store_true", help="regenerate it instead of failing")
    p.set_defaults(func=check)
    args = parser.parse_args()
    args.func(args)


if __name__ == "__main__":
    main()
